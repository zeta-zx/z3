import { randomUUID } from 'node:crypto';
import { setTimeout as sleep } from 'node:timers/promises';
import {
    DISCORD_PEER_PREFIX, DISCORD_PROTOCOL, DISCORD_REQUEST_LIFETIME,
} from '../src/lib/wayship-discord.ts';

const API = 'https://wayship.link/api';
const PEER_ID = /^[A-Za-z0-9._:-]{4,64}$/;
const DISCOVERY_TIMEOUT = 4000;

export class BotError extends Error {}

export const wayshipConnectUrl = 'https://wayship.link/connect?' + new URLSearchParams({
    app: 'zeta', name: 'Zeta Discord Bot', device_name: 'Discord Bot',
});

export function wayshipClient(fetcher = fetch) {
    async function api(token, path, body, deadline = Date.now() + 5000) {
        const remaining = deadline - Date.now();
        if (remaining <= 0) throw new BotError('Wayship did not reply in time.');
        const response = await fetcher(API + path, {
            method: body ? 'POST' : 'GET',
            signal: AbortSignal.timeout(Math.min(5000, remaining)),
            redirect: 'error',
            headers: {
                Authorization: `Bearer ${token}`,
                'Content-Type': 'application/json',
            },
            body: body ? JSON.stringify(body) : undefined,
        }).catch(() => { throw new BotError('Could not reach Wayship. Try again in a moment.'); });
        if (response.status === 401 || response.status === 403) {
            throw new BotError('Wayship rejected the connection. Open /wayship to connect again.');
        }
        if (!response.ok) throw new BotError(`Wayship returned HTTP ${response.status}.`);
        return response.json();
    }

    async function verify(token) {
        if (!/^wsa_[A-Za-z0-9_.-]{10,2000}$/.test(token)) {
            throw new BotError('Paste the app token generated by the Wayship button.');
        }
        const me = await api(token, '/apps/me');
        if (me.app !== 'zeta' || !me.account_id || !me.scopes?.includes('peers')) {
            throw new BotError('Connect using the Zeta Discord Bot link in /wayship.');
        }
        return { token, handle: me.handle, connectionId: me.conn_id };
    }

    async function session(token, run) {
        if (!token) throw new BotError('Connect your Wayship account with /wayship first.');
        const peerId = DISCORD_PEER_PREFIX + randomUUID();
        const { peers } = await api(token, '/peers/announce', {
            peer_id: peerId, device_name: 'Discord Bot', meta: { platform: 'discord' },
        });
        const devices = peers.filter((peer) => typeof peer.peer_id === 'string' && PEER_ID.test(peer.peer_id) &&
            peer.peer_id.startsWith('zeta-') && !peer.peer_id.startsWith(DISCORD_PEER_PREFIX))
            .map((peer) => ({
                id: peer.peer_id,
                name: (typeof peer.device_name === 'string' ? peer.device_name.trim().slice(0, 60) : '') || 'Zeta device',
            }))
            .sort((a, b) => a.id.localeCompare(b.id));

        async function request(targets, command, timeout) {
            const pending = new Map();
            const replies = [];
            const deadline = Date.now() + timeout;
            await Promise.all(targets.map(async (device) => {
                const requestId = randomUUID();
                try {
                    await api(token, '/peers/signal', {
                        from_peer: peerId, to_peer: device.id, kind: 'data',
                        payload: { ...command, protocol: DISCORD_PROTOCOL, requestId, expiresAt: deadline },
                    }, deadline);
                    pending.set(requestId, device);
                } catch (error) {
                    if (targets.length === 1) throw error;
                }
            }));

            while (pending.size && Date.now() < deadline) {
                const { events } = await api(token, `/peers/poll?peer_id=${encodeURIComponent(peerId)}`, undefined, deadline)
                    .catch((error) => {
                        if (Date.now() >= deadline) return { events: [] };
                        throw error;
                    });
                for (const event of events ?? []) {
                    const payload = event.payload;
                    if (event.kind !== 'signal' || event.signal_kind !== 'data' || event.to_peer !== peerId ||
                        payload?.protocol !== DISCORD_PROTOCOL || typeof payload.ok !== 'boolean') continue;
                    const device = pending.get(payload.requestId);
                    if (!device || device.id !== event.from_peer) continue;
                    pending.delete(payload.requestId);
                    replies.push({ ...device, result: payload });
                }
                const remaining = deadline - Date.now();
                if (pending.size && remaining > 0) await sleep(Math.min(remaining, 350));
            }
            return replies;
        }

        try {
            return await run(devices, request);
        } finally {
            await api(token, '/peers/leave', { peer_id: peerId }, Date.now() + 1000).catch(() => {});
        }
    }

    async function devices(token) {
        return session(token, async (online, request) => {
            const replies = await request(online.slice(0, 15), { action: 'status' }, DISCOVERY_TIMEOUT);
            return online.map((device) => ({
                ...device,
                playback: replies.find(({ id, result }) => id === device.id && result.ok)?.result.playback,
            }));
        });
    }

    async function run(token, command, deviceName) {
        return session(token, async (online, request) => {
            if (!online.length) throw new BotError('Open Zeta on a device connected to the same Wayship account.');
            const candidates = deviceName ? matchDevices(online, deviceName) : online.slice(0, 15);
            const replies = await request(candidates, { action: 'status' }, DISCOVERY_TIMEOUT);
            const available = replies.filter(({ result }) => result.ok && result.playback);
            if (!available.length) {
                throw new BotError('No player replied. Open Zeta with Discord bot support and try again.');
            }

            const readOnly = ['status', 'lyrics', 'album', 'activity-media'].includes(command.action);
            const voice = command.action === 'voice-start';
            const eligible = available.filter(({ result }) => (result.playback.controllable || readOnly) &&
                (!voice || result.playback.voiceAvailable));
            if (!eligible.length) {
                if (voice) throw new BotError('Open the updated desktop Zeta music player on the computer running the bot.');
                throw new BotError('The available devices are following another player. Open or select the playback host.');
            }
            const [device] = eligible.sort((a, b) => rank(b.result.playback) - rank(a.result.playback) ||
                a.id.localeCompare(b.id));
            if (command.action === 'status') return device;

            // Playback commands go to exactly one target. Never retry a command
            // on another device after a missing reply, since it may have run.
            const [reply] = await request([device], command, DISCORD_REQUEST_LIFETIME);
            if (!reply) throw new BotError('Zeta did not confirm the command. Check the player before repeating it.');
            if (!reply.result.ok) throw new BotError(String(reply.result.error || 'Zeta could not complete the command.'));
            return reply;
        });
    }

    return { verify, devices, run };
}

function rank(playback) {
    const phases = { playing: 3, loading: 2, paused: 1, idle: 0 };
    return (phases[playback.phase] ?? 0) * 2 + Number(!!playback.controllable);
}

function matchDevices(online, name) {
    const query = name.trim().toLowerCase();
    const exactId = online.find(({ id }) => id.toLowerCase() === query);
    if (exactId) return [exactId];
    const matches = online.filter((device) => device.name.toLowerCase() === query);
    if (matches.length > 1) throw new BotError('Several devices have that name. Copy a device ID from /devices.');
    if (!matches.length) throw new BotError('That device is offline or unknown. Use /devices to see what’s online.');
    return matches;
}
